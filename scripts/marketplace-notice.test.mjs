import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { smokeEnvironment } from './smoke-environment.mjs';

test('legacy notice updates only README once, without creating a missing marketplace branch', async t => {
  const fixture = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'cuefluent-notice-')));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  const remote = path.join(fixture, 'remote.git'), checkout = path.join(fixture, 'checkout');
  await fs.mkdir(checkout);
  const env = { ...smokeEnvironment(fixture), GIT_CONFIG_NOSYSTEM: '1', GITHUB_WORKSPACE: checkout, RUNNER_TEMP: fixture };
  const run = (cmd, args) => {
    const result = spawnSync(cmd, args, { cwd: checkout, env, encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  };
  const git = (...args) => run('git', ['-c', 'commit.gpgsign=false', ...args]);
  const script = fileURLToPath(new URL('./marketplace-notice.sh', import.meta.url));
  const template = fileURLToPath(new URL('../packaging/marketplace-moved.md', import.meta.url));
  git('init', '--bare', '--initial-branch=main', remote);
  git('init', '--initial-branch=main');
  git('config', 'user.name', 'Synthetic Notice'); git('config', 'user.email', 'notice@example.invalid');
  await fs.writeFile(path.join(checkout, 'README.md'), 'Historical instructions.');
  await fs.writeFile(path.join(checkout, 'package.txt'), 'Published package bytes.');
  git('add', '.'); git('commit', '-m', 'chore: seed old snapshot');
  git('remote', 'add', 'origin', remote); git('push', 'origin', 'main');
  const original = git('rev-parse', 'HEAD');
  await fs.mkdir(path.join(checkout, 'packaging'));
  await fs.copyFile(template, path.join(checkout, 'packaging/marketplace-moved.md'));
  run('bash', [script]);
  assert.equal(git('--git-dir', remote, 'for-each-ref', '--format=%(refname)', 'refs/heads'), 'refs/heads/main');
  git('push', 'origin', `${original}:refs/heads/marketplace`);
  run('bash', [script]);
  const updated = git('--git-dir', remote, 'rev-parse', 'marketplace');
  assert.notEqual(updated, original);
  assert.equal(git('--git-dir', remote, 'diff-tree', '--no-commit-id', '--name-only', '-r', updated), 'README.md');
  assert.equal(git('--git-dir', remote, 'show', 'marketplace:README.md'), (await fs.readFile(template, 'utf8')).trim());
  run('bash', [script]);
  assert.equal(git('--git-dir', remote, 'rev-parse', 'marketplace'), updated);
  assert.equal(git('--git-dir', remote, 'rev-parse', 'main'), original);
  assert.equal(git('rev-parse', 'HEAD'), original);
  assert.equal(git('diff', '--cached'), '');
});
